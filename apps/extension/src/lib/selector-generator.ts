import { MAX_SELECTOR_LENGTH } from "@remarks/shared";

export type SelectorStrategy = "id" | "data-testid" | "class" | "nth-child-path";

export interface GeneratedSelector {
  selector: string;
  strategy: SelectorStrategy;
}

const MAX_ANCESTORS = 4;
const MAX_CLASSES_PER_NODE = 2;

// React useId (":r1:", ":R0:", ":r1u:", etc.), CSS Modules hashes, UUID prefixes,
// Emotion/stitches generated classes.
const AUTO_ID_PATTERNS: readonly RegExp[] = [
  /^:[rR][0-9a-z]+:?$/,
  /^[a-f0-9]{8}-[a-f0-9]{4}-[a-f0-9]{4}/i,
  /^__[a-zA-Z]+_/,
  /^[a-zA-Z]+__[A-Za-z0-9]{5,}$/,
];

const UTILITY_CLASS_PATTERNS: readonly RegExp[] = [
  /^(sm|md|lg|xl|2xl|hover|focus|focus-visible|active|disabled|dark|group|peer):/,
  /^(w|h|p|px|py|pt|pb|pl|pr|m|mx|my|mt|mb|ml|mr|gap|space)-/,
  /^(flex|grid|block|inline|inline-block|inline-flex|hidden|contents|table)$/,
  /^(flex|grid|items|justify|content|self|place)-/,
  /^(text|bg|border|ring|shadow|outline|fill|stroke|from|via|to)-/,
  /^(rounded|opacity|z|order|cursor|overflow|pointer-events|select|whitespace|break|truncate)-/,
  /^(top|right|bottom|left|inset|absolute|relative|fixed|sticky|static)(-|$)/,
  /^(transition|duration|ease|delay|animate|transform|scale|rotate|translate|skew|origin)-/,
  /^\[.+\]$/,
  /^.+-\[.+\]$/,
];

function isAutoGeneratedId(id: string): boolean {
  return AUTO_ID_PATTERNS.some((re) => re.test(id));
}

function isUtilityClass(cls: string): boolean {
  return UTILITY_CLASS_PATTERNS.some((re) => re.test(cls));
}

function isReservedNamespaceClass(cls: string): boolean {
  return cls.startsWith("rmk-") || cls.startsWith("db-") || cls.startsWith("moat-");
}

function meaningfulClasses(el: Element, limit: number): string[] {
  const out: string[] = [];
  for (const cls of el.classList) {
    if (!cls) continue;
    if (isUtilityClass(cls)) continue;
    if (isReservedNamespaceClass(cls)) continue;
    out.push(cls);
    if (out.length >= limit) break;
  }
  return out;
}

function validateUnique(selector: string, target: Element, doc: Document): boolean {
  if (selector.length > MAX_SELECTOR_LENGTH) return false;
  try {
    const matches = doc.querySelectorAll(selector);
    return matches.length === 1 && matches[0] === target;
  } catch {
    return false;
  }
}

function tagName(el: Element): string {
  // SVG elements preserve case in tagName; lowercase for HTML only so selectors
  // stay case-correct for both.
  return el.namespaceURI === "http://www.w3.org/2000/svg" ? el.tagName : el.tagName.toLowerCase();
}

function nthChildIndex(el: Element): number | null {
  const parent = el.parentElement;
  if (!parent) return null;
  const siblings = Array.from(parent.children);
  const sameTag = siblings.filter((s) => s.tagName === el.tagName);
  if (sameTag.length <= 1) return null;
  return siblings.indexOf(el) + 1;
}

function buildPathStep(el: Element): string {
  let step = tagName(el);
  const classes = meaningfulClasses(el, MAX_CLASSES_PER_NODE).map((c) => `.${CSS.escape(c)}`);
  step += classes.join("");
  const nth = nthChildIndex(el);
  if (nth !== null) {
    step += `:nth-child(${nth})`;
  }
  return step;
}

function generatePathSelector(el: Element): string {
  const stack: string[] = [];
  let node: Element | null = el;
  let depth = 0;
  const doc = el.ownerDocument;
  const stopAt: Element | null = doc?.body ?? null;

  while (node && node !== stopAt && depth < MAX_ANCESTORS * 4) {
    // If an ancestor has a safe id, anchor the path there and stop walking.
    if (node.id && !isAutoGeneratedId(node.id)) {
      stack.unshift(`#${CSS.escape(node.id)}`);
      return stack.join(" > ");
    }
    stack.unshift(buildPathStep(node));
    node = node.parentElement;
    depth++;
  }

  return stack.slice(-MAX_ANCESTORS).join(" > ");
}

export function generateSelector(
  el: Element,
  doc: Document = el.ownerDocument ?? document
): GeneratedSelector {
  // 1. id
  if (el.id && !isAutoGeneratedId(el.id)) {
    const selector = `#${CSS.escape(el.id)}`;
    if (validateUnique(selector, el, doc)) {
      return { selector, strategy: "id" };
    }
  }

  // 2. data-testid (tag-qualified)
  const testId = el.getAttribute("data-testid");
  if (testId) {
    const selector = `${tagName(el)}[data-testid="${CSS.escape(testId)}"]`;
    if (validateUnique(selector, el, doc)) {
      return { selector, strategy: "data-testid" };
    }
  }

  // 3. tag + up to two meaningful classes
  const classes = meaningfulClasses(el, MAX_CLASSES_PER_NODE).map((c) => `.${CSS.escape(c)}`);
  if (classes.length > 0) {
    const selector = `${tagName(el)}${classes.join("")}`;
    if (validateUnique(selector, el, doc)) {
      return { selector, strategy: "class" };
    }
  }

  // 4. Path walk with nth-child fallbacks
  return { selector: generatePathSelector(el), strategy: "nth-child-path" };
}
